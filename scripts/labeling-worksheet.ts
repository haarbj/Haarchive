// Writes labeling-worksheet.md -- every day the structured-distance/steps
// layer (framework-structure.ts, post-race.ts's hand-filled recovery
// distances) could not resolve unambiguously, for Brody to label by hand.
// A follow-up task reads his answers back in; this script only produces
// the blank form.

import { writeFileSync } from "node:fs";
import path from "node:path";
import type { WorksheetEntry } from "@/lib/private-coaching/framework-structure";

export function writeLabelingWorksheet(entries: WorksheetEntry[], outDir: string = process.cwd()): string {
  const byProgram = new Map<string, WorksheetEntry[]>();
  for (const entry of entries) {
    const list = byProgram.get(entry.program) ?? [];
    list.push(entry);
    byProgram.set(entry.program, list);
  }

  const sections = [...byProgram.entries()].map(([program, programEntries]) => {
    const rows = programEntries
      .sort((a, b) => a.week - b.week || a.day - b.day)
      .map(
        (e) =>
          `### Week ${e.week}, Day ${e.day}\n\n` +
          `**Prescription (verbatim):** ${e.prescription.replace(/\n/g, " / ")}\n\n` +
          `**Question:** ${e.question}\n\n` +
          `**Brody's answer:** _(fill in here -- a total distance in miles, or whatever the question above actually calls for)_\n`,
      )
      .join("\n---\n\n");
    return `## ${program}\n\n${rows}`;
  });

  const content =
    `# Labeling worksheet -- seeded program structured data\n\n` +
    `Generated by scripts/seed-framework-programs.ts. Every day below is one the structured-distance/step parser (framework-structure.ts) or the recovery program's hand-filled distances (post-race.ts) could not resolve unambiguously on its own -- each entry states the verbatim prescription and the specific question that's actually open, with option sketches where relevant (never a silent guess). Fill in "Brody's answer" per day; a follow-up task reads this file back in and encodes the answers into the same structured-distance/step layer.\n\n` +
    `**${entries.length} day(s) total**, across ${byProgram.size} program(s).\n\n---\n\n` +
    sections.join("\n\n---\n\n");

  const outPath = path.join(outDir, "labeling-worksheet.md");
  writeFileSync(outPath, content, "utf8");
  return outPath;
}
