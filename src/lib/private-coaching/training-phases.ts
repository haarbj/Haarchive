import { mostRecentMonday, addDays } from "@/lib/week";
import { type DayTypeAccent } from "@/lib/private-coaching/day-type-visuals";

// Explicit, coach-defined training phases (Base/Build/Peak/Taper/etc.) --
// never inferred from mileage/intensity/workout types. See the
// training_phases migration's own comment for the full reasoning.
export type TrainingPhase = {
  id: string;
  athleteId: string;
  phaseType: string;
  name: string | null;
  startDate: string; // ISO date
  endDate: string; // ISO date
  goalId: string | null;
  notes: string | null;
  /** The athlete's own copy of "why this phase," written at assignment time (or by hand) and deliberately immune to later edits of the Program it came from. Null falls back to the standard copy for this phase type -- see phase-explainers.ts. */
  explainer: string | null;
  /** Set only when this phase was generated by assigning a Program -- see program-generation.ts and the provenance migration. Drives whether "Resync from program" is offered. */
  sourceProgramId: string | null;
  /** The specific program phase this was generated from, when it was. Lets a coach jump straight back to the phase they'd edit to change the explainer for future assignments. */
  sourceProgramPhaseDefinitionId: string | null;
};

export const SUGGESTED_PHASE_TYPES = ["Base", "Build", "Peak", "Taper", "Recovery", "Transition", "Race"];

// Kept intentionally minimal -- a handful of entries reusing the same
// accent tokens day_label already uses (day-type-visuals.ts), not a new
// visual subsystem. phase_type is a label the coach chose; the color is
// decorative recognition, never a signal about training content.
const PHASE_TYPE_ACCENTS: Record<string, DayTypeAccent> = {
  base: "forest",
  build: "warning",
  peak: "research",
  taper: "tip",
  recovery: "success",
  transition: "neutral",
  race: "navy",
};

export function getPhaseTypeAccent(phaseType: string): DayTypeAccent {
  return PHASE_TYPE_ACCENTS[phaseType.trim().toLowerCase()] ?? "neutral";
}

// A week's phase is whichever phase's date range contains THAT WEEK'S
// MONDAY -- never split, never majority-of-days, never coach-assigned per
// week. This is correct only because phases are treated as Monday-aligned
// coaching blocks throughout this product. Worked example: Phase A runs
// Aug 24-Sep 20, Phase B runs Sep 21-Oct 18 -- the week beginning Sep 21
// is Phase B in full. If a coach instead set Phase A to end Sep 23, the
// week beginning Sep 21 is STILL 100% Phase A, even though 3 of its 7 days
// fall inside Phase B's range -- not prohibited, but a coach relying on
// this function should understand the rule (the "+ Add phase" form nudges
// toward Monday/Sunday-aligned dates for exactly this reason).
export function getPhaseForWeek(phases: TrainingPhase[], weekStart: string): TrainingPhase | null {
  return phases.find((p) => weekStart >= p.startDate && weekStart <= p.endDate) ?? null;
}

// Every Monday whose week falls entirely within [startDate, endDate] --
// the pure date-math core of weeksInPhase, factored out so Phase View can
// reuse the identical enumeration for a gap BETWEEN two phases (an
// "Unphased" section) without needing a synthetic TrainingPhase object.
export function mondaysInRange(startDate: string, endDate: string): string[] {
  const firstMonday = mostRecentMonday(new Date(`${startDate}T00:00:00Z`));
  const weeks: string[] = [];
  let current = firstMonday >= startDate ? firstMonday : addDays(firstMonday, 7);
  while (current <= endDate) {
    weeks.push(current);
    current = addDays(current, 7);
  }
  return weeks;
}

// Every Monday from a phase's start_date through its end_date -- derived
// purely from date math, deliberately never touching training_week_plans.
// A coach creating "Base, Aug 24-Sep 20" gets 4 weeks here immediately,
// with zero training_week_plans rows required to exist first.
export function weeksInPhase(phase: TrainingPhase): string[] {
  return mondaysInRange(phase.startDate, phase.endDate);
}

// 1-indexed position of `weekStart` within `phase`'s own week list, and
// the total week count -- powers Week View's "Week 3 of 5" line. Returns
// null if the week isn't actually inside the phase (shouldn't happen when
// called with the result of getPhaseForWeek, but stays honest rather than
// returning a made-up position).
export function weekPositionInPhase(phase: TrainingPhase, weekStart: string): { week: number; of: number } | null {
  const weeks = weeksInPhase(phase);
  const index = weeks.indexOf(weekStart);
  if (index === -1) return null;
  return { week: index + 1, of: weeks.length };
}

// Total number of weeks a phase spans (Sunday-inclusive), for Phase
// View's "Aug 24 - Sep 20 · 4 weeks" header line.
export function phaseWeekCount(phase: TrainingPhase): number {
  return weeksInPhase(phase).length;
}

export type RoadmapSection = { kind: "phase"; phase: TrainingPhase } | { kind: "unphased"; weeks: string[] };

// The single canonical "which weeks belong to which phase, and which gaps
// are Unphased" computation -- both the server page (which needs a flat
// week list to query training_week_plans for) and Phase View itself
// (which needs the structured breakdown to render) call this exact
// function, so the two can never silently drift apart the way computing
// the same gap logic twice would risk.
export function buildRoadmapSections(phases: TrainingPhase[]): RoadmapSection[] {
  const sorted = [...phases].sort((a, b) => a.startDate.localeCompare(b.startDate));
  const sections: RoadmapSection[] = [];
  sorted.forEach((phase, index) => {
    sections.push({ kind: "phase", phase });
    const next = sorted[index + 1];
    if (next) {
      const gapStart = addDays(phase.endDate, 1);
      const gapEnd = addDays(next.startDate, -1);
      if (gapStart <= gapEnd) {
        const gapWeeks = mondaysInRange(gapStart, gapEnd);
        if (gapWeeks.length > 0) sections.push({ kind: "unphased", weeks: gapWeeks });
      }
    }
  });
  return sections;
}

// Every week the roadmap will actually render, flattened -- exactly what
// the server page needs to bound its training_week_plans query to.
export function roadmapWeeks(phases: TrainingPhase[]): string[] {
  return buildRoadmapSections(phases).flatMap((section) =>
    section.kind === "phase" ? weeksInPhase(section.phase) : section.weeks,
  );
}
